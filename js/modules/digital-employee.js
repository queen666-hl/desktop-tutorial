function init_digital_employee() {
  if (window._deInited) return;
  renderEmployees();
  selectEmployee(0, false);
  $('#chatSend').addEventListener('click', sendMsg);
  $('#chatInput').addEventListener('keydown', e => { if (e.key === 'Enter') sendMsg(); });
  window._deInited = true;
}

function renderEmployees() {
  $('#employeeList').innerHTML = EMPLOYEES.map((e, i) => `
    <div class="employee-item" data-idx="${i}" onclick="selectEmployee(${i})">
      <div class="avatar">${e.ico}</div>
      <div style="flex:1">
        <div class="emp-name">${e.name}</div>
        <div class="emp-role">${e.role} · ${e.tasks}</div>
      </div>
      <span class="emp-status">${e.status}</span>
    </div>
  `).join('');
}

/* 切换数字员工 */
function selectEmployee(idx, showSwitchTip = true) {
  const emp = EMPLOYEES[idx];
  if (!emp) return;
  currentEmployee = emp;
  $$('.employee-item').forEach((el, i) => el.classList.toggle('active', i === idx));
  const head = $('#module-digital-employee .chat-head');
  head.querySelector('.avatar').textContent = emp.ico;
  head.querySelector('.persona-name').textContent = `${emp.name} · ${emp.role}`;
  $('#chatBody').innerHTML = '';
  const greeting = EMPLOYEE_GREETINGS[emp.name] || `您好~我是${emp.name}，很高兴为您服务。`;
  appendMsg('ai', greeting);
  if (showSwitchTip) toast(`已切换到 ${emp.name}`, 'success');
}

