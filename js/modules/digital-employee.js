/* 兜底回复：不清楚就如实说，不编造 */
const FALLBACK_REPLY = `这个问题问得挺专业的，为了不给您说错，我去跟业务那边确认一下哈~
您先把问题再描述清楚点，或者发下订单号/截图，我马上回来告诉您。还有其他疑问吗？`;

function sendMsg() {
  const input = $('#chatInput');
  const text = input.value.trim();
  if (!text) return;
  appendMsg('me', text);
  input.value = '';
  setTimeout(() => {
    let reply = FALLBACK_REPLY;
    for (const intent of AI_INTENTS) {
      if (intent.keywords.some(k => text.includes(k))) {
        reply = intent.reply;
        break;
      }
    }
    appendMsg('ai', reply);
  }, 320);
}

function appendMsg(role, text) {
  const body = $('#chatBody');
  const div = document.createElement('div');
  div.className = `msg ${role === 'me' ? 'me' : ''}`;
  const aiIcon = currentEmployee ? currentEmployee.ico : 'AI';
  div.innerHTML = `<div class="avatar" style="${role === 'ai' ? 'background:linear-gradient(135deg,#a78bfa,#22d3ee)' : ''}">${role === 'me' ? '我' : aiIcon}</div><div class="bubble">${text.replace(/\n/g, '<br>')}</div>`;
  body.appendChild(div);
  body.scrollTop = body.scrollHeight;
}
